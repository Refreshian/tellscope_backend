def add_table_of_contents(doc):
    """Добавление оглавления (заполнится автоматически в Word)"""
    doc.add_heading('ОГЛАВЛЕНИЕ', level=1)
    
    paragraph = doc.add_paragraph()
    run = paragraph.add_run()
    fldChar = OxmlElement('w:fldChar')
    fldChar.set(qn('w:fldCharType'), 'begin')
    run._r.append(fldChar)
    
    instrText = OxmlElement('w:instrText')
    instrText.set(qn('xml:space'), 'preserve')
    instrText.text = 'TOC \\o "1-3" \\h \\z \\u'
    run._r.append(instrText)
    
    fldChar = OxmlElement('w:fldChar')
    fldChar.set(qn('w:fldCharType'), 'end')
    run._r.append(fldChar)
    
    doc.add_paragraph('(Оглавление обновится при открытии документа в MS Word - щелкните правой кнопкой и выберите "Обновить поле")')
    doc.add_page_break()
    
    return doc

def add_section(doc, heading, content, level=1):
    """Добавление раздела с автоформатированием"""
    # Заголовок
    doc.add_heading(heading, level=level)
    
    # Обработка контента
    paragraphs = content.split('\n\n')
    
    for para in paragraphs:
        para = para.strip()
        if not para:
            continue
            
        # Проверка на список
        if para.startswith('•') or para.startswith('-') or para.startswith('*'):
            lines = para.split('\n')
            for line in lines:
                line = line.strip()
                if line:
                    # Удаляем маркер списка в начале
                    line = line.lstrip('•-* ').strip()
                    doc.add_paragraph(line, style='List Bullet')
        
        # Проверка на нумерованный список
        elif para[0].isdigit() and ('. ' in para[:5] or ') ' in para[:5]):
            lines = para.split('\n')
            for line in lines:
                line = line.strip()
                if line and line[0].isdigit():
                    # Удаляем номер в начале
                    line = line.split('.', 1)[-1].split(')', 1)[-1].strip()
                    doc.add_paragraph(line, style='List Number')
        
        # Обычный абзац
        else:
            doc.add_paragraph(para)
    
    return doc

