def ask_model(prompt, model=MODEL_NAME, max_tokens=MAX_TOKENS, temperature=TEMPERATURE):
    """Отправка запроса к модели с обработкой ошибок"""
    try:
        print(f"\n{'='*70}")
        print(f"🤖 Запрос к модели {model}...")
        print(f"📝 Промпт: {prompt[:150]}..." if len(prompt) > 150 else f"📝 Промпт: {prompt}")
        
        response = client.chat.completions.create(
            messages=[{"role": "user", "content": prompt}],
            model=model,
            max_tokens=max_tokens,
            temperature=temperature,
        )
        
        content = response.choices[0].message.content
        tokens_used = response.usage.total_tokens if hasattr(response, 'usage') else 0
        
        print(f"✅ Получен ответ: {len(content)} символов, ~{tokens_used} токенов")
        print(f"{'='*70}\n")
        
        return content
        
    except Exception as e:
        print(f"❌ Ошибка при обращении к API: {e}")
        return None

