def generate_lecture():
    """Главная функция: генерация всей лекции"""
    
    print("\n" + "="*70)
    print("🚀 ЗАПУСК ГЕНЕРАТОРА РАСШИРЕННОЙ ЛЕКЦИИ ПО ИСП-АЭС")
    print("="*70)
    
    # Создание документа
    doc = Document()
    doc = setup_document_styles(doc)
    
    # Титульная страница
    print("\n📄 Создание титульной страницы...")
    doc = add_title_page(doc)
    
    # Оглавление
    print("📑 Добавление оглавления...")
    doc = add_table_of_contents(doc)
    
    # Генерация разделов
    total_sections = len(LECTURE_SECTIONS)
    
    for i, section in enumerate(LECTURE_SECTIONS, 1):
        print(f"\n{'='*70}")
        print(f"📝 РАЗДЕЛ {section['number']}/{total_sections}: {section['title']}")
        print(f"{'='*70}")
        
        # Запрос к модели
        content = ask_model(section['prompt'])
        
        if content:
            # Добавление в документ
            add_section(doc, f"{section['number']}. {section['title']}", content, level=1)
            print(f"✅ Раздел {section['number']} добавлен в документ")
        else:
            print(f"❌ Ошибка генерации раздела {section['number']}")
            # Добавляем заглушку
            doc.add_heading(f"{section['number']}. {section['title']}", level=1)
            doc.add_paragraph("[Содержимое раздела не сгенерировано из-за ошибки API]")
        
        # Задержка между запросами
        if i < total_sections:
            print(f"\n⏳ Пауза {DELAY_BETWEEN_REQUESTS} сек перед следующим запросом...")
            time.sleep(DELAY_BETWEEN_REQUESTS)
    
    # ДОПОЛНИТЕЛЬНО: Поиск информации о производителях через модель sonar
    print("\n" + "="*70)
    print("🔍 ПОИСК АКТУАЛЬНОЙ ИНФОРМАЦИИ О ПРОИЗВОДИТЕЛЯХ (модель sonar)...")
    print("="*70)
    
    manufacturers_info = search_manufacturers_info()
    
    if manufacturers_info:
        # Находим раздел 17 (Производители) и дополняем его
        print("✅ Информация о производителях получена")
        # Можно добавить как подраздел или заменить содержимое раздела 17
        # Для простоты добавим как отдельный подраздел
        doc.add_heading("17.1. Актуальная информация о производителях (дополнение)", level=2)
        doc.add_paragraph(manufacturers_info)
    else:
        print("⚠️ Не удалось получить информацию о производителях через sonar")
    
    # Сохранение документа
    print("\n" + "="*70)
    print(f"💾 Сохранение документа: {OUTPUT_FILE}")
    print("="*70)
    
    try:
        doc.save(OUTPUT_FILE)
        print(f"\n✅ УСПЕХ! Документ сохранен: {OUTPUT_FILE}")
        print(f"📊 Количество разделов: {total_sections}")
        print(f"📄 Примерный объем: {total_sections * 4} страниц")
        print("\n💡 Рекомендации:")
        print("   1. Откройте документ в MS Word")
        print("   2. Обновите оглавление (правый клик → Обновить поле)")
        print("   3. Проверьте форматирование")
        print("   4. При необходимости отредактируйте содержимое")
        
    except Exception as e:
        print(f"\n❌ ОШИБКА при сохранении: {e}")
        return False
    
    return True

